//! Модуль общих данных: начальная позиция камеры и список графических
//! объектов сцены. После запуска данные хранятся в мире Bevy: объекты —
//! в виде сущностей, камера — в виде ресурса CameraRig.

use bevy::prelude::*;

use crate::graphic_object::GraphicObject;

/// Начальная позиция камеры, согласованная с третьей лабораторной работой.
pub fn initial_camera_position() -> Vec3 {
    Vec3::new(10.0, 15.0, 17.5)
}

/// Возвращает список графических объектов сцены.
pub fn scene_objects() -> Vec<GraphicObject> {
    vec![
        // Красный — справа (+X), угол 180°.
        GraphicObject::new(Vec3::new(4.0, 0.0, 0.0), 180.0, Vec3::new(1.0, 0.0, 0.0)),
        // Синий — слева (-X), угол 0°.
        GraphicObject::new(Vec3::new(-4.0, 0.0, 0.0), 0.0, Vec3::new(0.0, 0.0, 1.0)),
        // Зелёный — сзади (-Z), угол 90°.
        GraphicObject::new(Vec3::new(0.0, 0.0, -4.0), 90.0, Vec3::new(0.0, 1.0, 0.0)),
        // Белый — спереди (+Z), угол 270°.
        GraphicObject::new(Vec3::new(0.0, 0.0, 4.0), 270.0, Vec3::new(1.0, 1.0, 1.0)),
    ]
}
